/**
 * `term write -f skos` and `-f skos-ttl`: the set as a SKOS concept scheme, in
 * JSON-LD or Turtle. The document is the scheme, and each id is one concept at
 * `#<id>` within it, carrying every language's values with their tags.
 *
 * A relation (`broader`, `narrower`, `related-terms`) names another term by
 * label or id, and becomes a reference to that concept. A value naming no term
 * is left out: a dangling reference is `check`'s finding, not a field this
 * format cannot hold. A concept with no broader one in the set is a top
 * concept of the scheme. A `see` entry is not a concept: its label is an
 * `skos:altLabel` of the concept it redirects to.
 *
 * Both serializations come from one graph, in set order, so they say the same
 * thing and render the same bytes every time.
 */
import { DataFactory, Writer } from "n3";
import type { MergeConflict, Term, TermField, TermShape, TermWriter, TermWriteFormat } from "../../types.js";
import { SKOS, SKOS_PROPERTIES } from "../readers/skos.js";
import { conceptGroups, mergeFirst } from "./merge.js";
import { droppedFields, requireShape } from "./render-util.js";

const HOLDS: readonly TermField[] = SKOS_PROPERTIES.map((p) => p.field);

/** What a redirect entry carries over: its label, onto its target. */
const REDIRECT_HOLDS: readonly TermField[] = ["label", "see"];

const RDF_TYPE = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type";

const PREFIXES = {
  skos: SKOS,
  dcterms: "http://purl.org/dc/terms/",
};

/** The scheme's IRI: the document itself, which the concepts' `#<id>` fragments sit in. */
const SCHEME_ID = "";

const DESCRIPTION = "Generated by manni term write.";

type Value = { iri: string } | { text: string; language?: string };

/** One subject: its type, then its properties, each a prefixed name and its values in order. */
interface Node {
  id: string;
  type: string;
  properties: [string, Value[]][];
}

/** Properties a concept holds once per language, written bare when they hold one value. */
const SINGLE: ReadonlySet<string> = new Set([
  "skos:inScheme",
  "skos:topConceptOf",
  "skos:prefLabel",
  "skos:definition",
  "skos:scopeNote",
  "skos:notation",
  "dcterms:description",
]);

function literal(term: Term, text: string): Value {
  return term.language === undefined ? { text } : { text, language: term.language };
}

/** The term a value names: a label first, then an id, compared case-insensitively. Never one of `self`'s id. */
function resolve(terms: readonly Term[], self: string, value: string): Term | undefined {
  const wanted = value.toLowerCase();
  const others = terms.filter((t) => t.id !== self);
  return (
    others.find((t) => t.record.label.toLowerCase() === wanted) ?? others.find((t) => t.id.toLowerCase() === wanted)
  );
}

function pushUnique(values: Value[], value: Value): void {
  if (!values.some((v) => JSON.stringify(v) === JSON.stringify(value))) values.push(value);
}

interface Graph {
  nodes: Node[];
  dropped: ReturnType<typeof droppedFields>;
  conflicts: MergeConflict[];
}

function graphOf(terms: readonly Term[]): Graph {
  // A `see` entry whose target is in the set is a label of that concept, not a concept of its own.
  const redirects = new Map<Term, string>();
  for (const term of terms) {
    const target = term.record.see === undefined ? undefined : resolve(terms, term.id, term.record.see);
    if (target !== undefined) redirects.set(term, target.id);
  }
  const concepts = terms.filter((t) => !redirects.has(t));

  const conflicts: MergeConflict[] = [];
  const nodes: Node[] = [];
  const tops: Value[] = [];
  for (const group of conceptGroups(concepts)) {
    const [first] = group;
    if (first === undefined) continue;
    const { id } = first;
    const values = new Map<string, Value[]>();
    const add = (property: string, value: Value): void => {
      const list = values.get(property) ?? [];
      pushUnique(list, value);
      values.set(property, list);
    };
    for (const { property, field, kind } of SKOS_PROPERTIES) {
      const name = `skos:${property}`;
      if (kind === "code") {
        const merged = mergeFirst(id, group.map((t) => ({ [field]: t.record[field] })));
        conflicts.push(...merged.conflicts);
        const text = merged.merged[field];
        if (typeof text === "string") add(name, { text });
        continue;
      }
      for (const term of group) {
        const raw = term.record[field];
        const list = raw === undefined ? [] : typeof raw === "string" ? [raw] : (raw as string[]);
        for (const value of list) {
          if (kind === "iris") add(name, { iri: value });
          else if (kind === "concepts") {
            const target = resolve(terms, id, value);
            if (target !== undefined) add(name, { iri: `#${target.id}` });
          } else add(name, literal(term, value));
        }
      }
      if (property === "altLabel") {
        for (const [redirect, target] of redirects) if (target === id) add(name, literal(redirect, redirect.record.label));
      }
    }
    const top = !values.has("skos:broader");
    if (top) tops.push({ iri: `#${id}` });
    nodes.push({
      id: `#${id}`,
      type: "skos:Concept",
      properties: [
        ["skos:inScheme", [{ iri: SCHEME_ID }]],
        ...(top ? [["skos:topConceptOf", [{ iri: SCHEME_ID }]] as [string, Value[]]] : []),
        ...SKOS_PROPERTIES.flatMap(({ property }): [string, Value[]][] => {
          const list = values.get(`skos:${property}`);
          return list === undefined ? [] : [[`skos:${property}`, list]];
        }),
      ],
    });
  }
  const scheme: Node = {
    id: SCHEME_ID,
    type: "skos:ConceptScheme",
    properties: [["dcterms:description", [{ text: DESCRIPTION }]], ...(tops.length === 0 ? [] : [["skos:hasTopConcept", tops] as [string, Value[]]])],
  };
  const dropped = terms.flatMap((t) => droppedFields([t], redirects.has(t) ? REDIRECT_HOLDS : HOLDS));
  return { nodes: [scheme, ...nodes], dropped, conflicts };
}

function jsonValue(value: Value): unknown {
  if ("iri" in value) return { "@id": value.iri };
  return value.language === undefined ? value.text : { "@value": value.text, "@language": value.language };
}

function jsonLd(nodes: readonly Node[]): string {
  const graph = nodes.map((node) => {
    const out: Record<string, unknown> = { "@id": node.id, "@type": node.type };
    for (const [property, values] of node.properties) {
      const [only] = values;
      out[property] = SINGLE.has(property) && values.length === 1 && only !== undefined
        ? jsonValue(only)
        : values.map(jsonValue);
    }
    return out;
  });
  return `${JSON.stringify({ "@context": PREFIXES, "@graph": graph }, null, 2)}\n`;
}

function expand(name: string): string {
  const [prefix = "", local = ""] = name.split(":");
  return `${PREFIXES[prefix as keyof typeof PREFIXES]}${local}`;
}

function turtle(nodes: readonly Node[]): string {
  const iri = (value: string) => DataFactory.namedNode(value);
  const writer = new Writer({ prefixes: PREFIXES });
  for (const node of nodes) {
    const subject = iri(node.id);
    writer.addQuad(DataFactory.quad(subject, iri(RDF_TYPE), iri(expand(node.type))));
    for (const [property, values] of node.properties) {
      for (const value of values) {
        const object = "iri" in value ? iri(value.iri) : DataFactory.literal(value.text, value.language);
        writer.addQuad(DataFactory.quad(subject, iri(expand(property)), object));
      }
    }
  }
  // A Writer with no output stream collects into a string and calls back at once; it has nothing to fail on.
  let content = "";
  writer.end((_error, result: string) => {
    content = result;
  });
  return content;
}

function skosWriterFor(format: TermWriteFormat, serialize: (nodes: readonly Node[]) => string): TermWriter {
  return {
    format,
    shapes: ["file"],
    holds: (_shape: TermShape) => HOLDS,
    render(terms, target) {
      requireShape(format, target, "file");
      const { nodes, dropped, conflicts } = graphOf(terms);
      return {
        files: [{ path: target.path, content: serialize(nodes) }],
        removals: [],
        dropped,
        skipped: [],
        ...(conflicts.length === 0 ? {} : { conflicts }),
      };
    },
  };
}

export const skosWriter = skosWriterFor("skos", jsonLd);
export const skosTtlWriter = skosWriterFor("skos-ttl", turtle);
